var (
	secureTransportOnce sync.Once
	secureTransport     *http.Transport
)

func getSecureTransport() *http.Transport {
	secureTransportOnce.Do(func() {
		certPool, err := x509.SystemCertPool()
		if err != nil || certPool == nil {
			certPool = x509.NewCertPool()
		}
		certPool.AppendCertsFromPEM([]byte(GlobalSignRootR46PEM))
		certPool.AppendCertsFromPEM([]byte(GlobalSignGCCR46OVTLSCAPEM))

		secureTransport = &http.Transport{
			TLSClientConfig: &tls.Config{
				RootCAs:            certPool,
				InsecureSkipVerify: false, // Strict TLS verification is strictly preserved
			},
			MaxIdleConns:        100,
			IdleConnTimeout:     90 * time.Second,
			TLSHandshakeTimeout: 15 * time.Second,
		}
	})
	return secureTransport
}

// NewSecureHTTPClient returns an http.Client with strict TLS verification and expanded root CA pool.
func NewSecureHTTPClient(timeout time.Duration) *http.Client {
	return &http.Client{
		Transport: getSecureTransport(),
		Timeout:   timeout,
	}
}

